export function getLanguage() {
  return localStorage.getItem(STORAGE_KEY) === "ar" ? "ar" : "en";
}

export function setLanguage(language) {
  const next = language === "ar" ? "ar" : "en";
  localStorage.setItem(STORAGE_KEY, next);
  return next;
}

export function t(key, replacements = {}, language = getLanguage()) {
  const source = strings[language]?.[key] ?? strings.en[key] ?? key;
  return Object.entries(replacements).reduce((value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)), source);
}

export function activityName(slug, short = false) {
  const suffix = short && slug === "gaming" ? ".short" : ".name";
  return t(`activity.${slug}${suffix}`);
}

export function activityLine(slug) {
  return t(`activity.${slug}.line`);
}

export function countLabel(value, unit) {
  const number = Number(value) || 0;
  if (getLanguage() === "en") {
    const labels = { point: "point", reward: "reward", scan: "scan", member: "member" };
    const label = labels[unit] || unit;
    return `${number} ${label}${Math.abs(number) === 1 ? "" : "s"}`;
  }
  const forms = {
    point: { zero: "0 نقطة", one: "نقطة واحدة", two: "نقطتان", few: `${number} نقاط`, many: `${number} نقطة`, other: `${number} نقطة` },
    reward: { zero: "0 مكافأة", one: "مكافأة واحدة", two: "مكافأتان", few: `${number} مكافآت`, many: `${number} مكافأة`, other: `${number} مكافأة` },
    scan: { zero: "0 عملية مسح", one: "عملية مسح واحدة", two: "عمليتا مسح", few: `${number} عمليات مسح`, many: `${number} عملية مسح`, other: `${number} عملية مسح` },
    member: { zero: "0 عضو", one: "عضو واحد", two: "عضوان", few: `${number} أعضاء`, many: `${number} عضوًا`, other: `${number} عضو` }
  };
  const category = new Intl.PluralRules("ar-AE").select(Math.abs(number));
  return forms[unit]?.[category] ?? `${number}`;
}

export function formatDubaiDateTime(value) {
  if (!value) return t("common.never");
  return new Intl.DateTimeFormat(getLanguage() === "ar" ? "ar-AE-u-nu-latn" : "en-AE", {
    timeZone: "Asia/Dubai", dateStyle: "medium", timeStyle: "short"
  }).format(new Date(value));
}

export function eventActionLabel(action) {
  const key = `event.${String(action || "").toLowerCase()}`;
  const translated = t(key);
  return translated === key ? String(action || "").replaceAll("_", " ") : translated;
}

export function localizeError(error) {
  const message = String(error?.message || error || "");
  if (getLanguage() !== "ar") return message;
  return errorTranslations[message] || "تعذّر إكمال الطلب. حاول مجددًا.";
}

export function applyDocumentLanguage() {
  const language = getLanguage();
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  document.title = t("meta.title", {}, language);
  document.querySelector('meta[name="description"]')?.setAttribute("content", t("meta.description", {}, language));
  return language;
}
